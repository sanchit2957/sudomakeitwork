export function generatePanIndiaHospitals() {
  const hospitals: any[] = [];
  let currentId = 100001;

  for (const stateMeta of STATES_DATA) {
    const targetPerState = 260; // Meets and exceeds the >=250 requirement per state
    const districts = stateMeta.districts;

    for (let i = 0; i < targetPerState; i++) {
      const district = districts[i % districts.length];
      const template = HOSPITAL_NAME_TEMPLATES[i % HOSPITAL_NAME_TEMPLATES.length];

      // Jitter coordinates naturally within 0.01 to 0.08 degrees (~1 km to ~9 km from district center)
      const latOffset = (((i * 17) % 100) / 1000) - 0.05;
      const lngOffset = (((i * 23) % 100) / 1000) - 0.05;
      const latitude = parseFloat((district.lat + latOffset).toFixed(6));
      const longitude = parseFloat((district.lng + lngOffset).toFixed(6));

      const orgName = `${template.replace("Hospital", "").replace("Center", "").trim()} Health Network`;
      const branchName = `${district.name} ${i >= districts.length ? `Sector ${Math.floor(i / districts.length) + 1}` : "Main Campus"}`;
      const fullName = `${template} — ${district.name} (${branchName})`;

      // Capacities
      const totalEr = 40 + ((i * 7) % 60); // 40 to 100
      const availEr = 10 + ((i * 3) % (totalEr - 15)); // at least 10 available
      const totalIcu = 15 + ((i * 5) % 25); // 15 to 40
      const availIcu = 4 + ((i * 2) % (totalIcu - 8)); // at least 4 available
      const oxygen = 40 + ((i * 11) % 120);
      const blood = 25 + ((i * 9) % 75);
      const ambulances = 3 + (i % 6);

      const pincode = `${stateMeta.pincodePrefix}${String(1000 + (i % 9000)).slice(0, 4)}`;
      const phone = `${stateMeta.phonePrefix} ${String(20000000 + (i * 137)).slice(0, 8)}`;

      hospitals.push({
        id: currentId++,
        ownerUserId: null,
        organizationName: orgName,
        branchName: branchName,
        registrationId: `IN-${stateMeta.state.slice(0, 2).toUpperCase()}-HFR-${currentId}`,
        isPrimaryBranch: i === 0,
        name: fullName,
        address: `Emergency Block, Near ${district.name} Highway, ${district.name}`,
        city: district.name,
        state: stateMeta.state,
        pincode: pincode,
        contactPhone: phone,
        specialty: SPECIALTY_OPTIONS[i % SPECIALTY_OPTIONS.length],
        latitude,
        longitude,
        totalEmergencyBeds: totalEr,
        availableEmergencyBeds: availEr,
        totalIcuBeds: totalIcu,
        availableIcuBeds: availIcu,
        oxygenCylinderCount: oxygen,
        bloodUnitCount: blood,
        ambulanceCount: ambulances,
        foodSupplyStatus: (i % 5 === 0) ? "limited" : "available",
        medicineSupplyStatus: (i % 7 === 0) ? "limited" : "available",
        waterSupplyStatus: "available",
        powerBackupStatus: "available",
        status: (i % 8 === 0) ? "limited" : "open",
        isSahayVerified: true,
        updatedAt: new Date().toISOString(),
      });
    }
  }

  return hospitals;
}

